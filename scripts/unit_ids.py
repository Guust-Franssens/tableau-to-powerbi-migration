"""
purpose: cross-run unit IDs (#836) - one never-reset counter per runs root, a per-run unit dictionary,
         the UNITS.md projection generated from it, and read-only lookup by ID, name or LUID.
usage:   library only - unit_ids.allocate_unit_ids(run_dir, [unit_ids.UnitRequest(key, kind, name)])
         read-only lookup: python -B scripts/t2p.py units list|show ID|find

Layout under one runs root (`<repo>/_runs/` by default, `<runs-parent>/_runs/` otherwise):

  .unit-id-reservations/<digits>/owner.json  permanent reservation plus owner pointer (run, key)
  <run>/unit-index.json                       canonical per-run dictionary (schema_version 1)
  <run>/UNITS.md                              projection of the index; regenerated, never edited
  <run>/unit-index.lock                       O_EXCL lock held only while one allocator writes

An ID is `u` plus its reservation number, zero-padded to at least four digits (u0001 .. u9999,
u10000). The next number is the highest ever reserved plus one, never a gap, and a reservation is
permanent even when its allocation was interrupted, so an ID can never name two units. A re-run
inside the same run reuses that run's ID for the exact same run-local key. A short ID is a lookup
key, not proof of source identity. Runs without an index are legacy and are never backfilled.

Allocation is not wired into run_estate.py yet; lookup is read-only and never allocates, renames,
refreshes, reads credentials or starts Desktop.
"""

from __future__ import annotations

from collections import Counter
import contextlib
import copy
from dataclasses import dataclass
from datetime import datetime, timezone
import json
import os
from pathlib import Path, PurePosixPath
import re
import secrets
import stat
from typing import Any, Iterator, Mapping, Sequence
from urllib.parse import quote

import work_dirs

INDEX_FILE_NAME = "unit-index.json"
README_FILE_NAME = "UNITS.md"
LOCK_FILE_NAME = "unit-index.lock"
OWNER_FILE_NAME = "owner.json"
INDEX_SCHEMA_VERSION = 1
OWNER_SCHEMA_VERSION = 1
LOOKUP_SCHEMA_VERSION = "unit-lookup/v1"
UNIT_KINDS = ("workbook", "datasource")
ARTIFACT_ROLES = ("project_file", "semantic_model", "report")
SOURCE_IDENTITY_FIELDS = ("luid", "site_luid", "project_luid", "project_name")
MIN_ID_WIDTH = 4

_RUN_MANIFEST = "run.json"
_MAX_ALLOCATION_ATTEMPTS = 50
_ID_RE = re.compile(r"u([0-9]{4,})")
_DIGITS_RE = re.compile(r"[0-9]+")
_OWNER_KEYS = frozenset({"schema_version", "id", "run", "key", "reserved"})
_UNIT_KEYS = frozenset({"id", "key", "source", "artifacts"})
_SOURCE_KEYS = frozenset({"kind", "name", *SOURCE_IDENTITY_FIELDS})
_README_MARKER = "<!-- Generated by scripts/unit_ids.py from unit-index.json; do not edit. -->"
_MARKDOWN_SPECIAL = frozenset("\\`*_[]<>|#!")
#: Which emitted artifact the README links: a workbook opens through its project file or report, a
#: datasource has no report and is navigated through its model.
_ARTIFACT_PREFERENCE = {
    "workbook": ("project_file", "report", "semantic_model"),
    "datasource": ("semantic_model", "project_file", "report"),
}


class UnitIdError(RuntimeError):
    """An allocation or index write was refused. The index was left as it was; any reservation
    already made by the refused call stays burned (D4)."""


class UnitIndexInvalid(UnitIdError):
    """A run's `unit-index.json` exists but cannot be trusted; `reason` is a fixed code."""

    def __init__(self, reason: str, detail: str) -> None:
        super().__init__(f"{reason}: {detail}")
        self.reason = reason


@dataclass(frozen=True)
class UnitRequest:
    """One unit to allocate. `key` is the exact run-local key (for example the run-relative input
    asset path); it is compared byte-for-byte, never by display-name similarity."""

    key: str
    kind: str
    name: str
    luid: str | None = None
    site_luid: str | None = None
    project_luid: str | None = None
    project_name: str | None = None


def format_unit_id(number: int) -> str:
    """`u` + the number zero-padded to at least `MIN_ID_WIDTH` digits; the width grows past 9999."""
    if isinstance(number, bool) or not isinstance(number, int) or number < 1:
        raise ValueError("a unit-ID number is a positive integer")
    return "u" + _reservation_name(number)


def parse_unit_id(text: object) -> int | None:
    """The number behind a canonical unit ID, or None. `u17` and `u00017` are not canonical."""
    match = _ID_RE.fullmatch(text) if isinstance(text, str) else None
    if match is None:
        return None
    number = int(match.group(1))
    return number if number >= 1 and format_unit_id(number) == text else None


def reservations_root(runs_root: Path) -> Path:
    """The runs-root metadata directory holding one permanent reservation per unit ID."""
    return Path(runs_root) / work_dirs.UNIT_ID_RESERVATIONS_DIR_NAME


def highest_reserved(runs_root: Path) -> int:
    """Highest number ever reserved under this runs root, 0 when none. Any digit-only name counts,
    canonical or not, so the counter can never move backwards."""
    try:
        names = [child.name for child in reservations_root(runs_root).iterdir()]
    except FileNotFoundError:
        return 0
    return max((int(name) for name in names if _DIGITS_RE.fullmatch(name)), default=0)


def _reservation_name(number: int) -> str:
    return str(number).zfill(MIN_ID_WIDTH)


def _utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _has_control(text: str) -> bool:
    return any(ord(char) < 0x20 or 0x7F <= ord(char) <= 0x9F for char in text)


def _reserve(runs_root: Path) -> int:
    """Claim the next number with an atomic `mkdir`, exactly like `work_dirs.allocate_run`."""
    root = reservations_root(runs_root)
    root.mkdir(parents=True, exist_ok=True)
    candidate = highest_reserved(runs_root) + 1
    for _attempt in range(_MAX_ALLOCATION_ATTEMPTS):
        try:
            (root / _reservation_name(candidate)).mkdir(exist_ok=False)
        except FileExistsError:
            candidate = max(candidate + 1, highest_reserved(runs_root) + 1)
            continue
        return candidate
    raise UnitIdError(f"no unit ID could be reserved after {_MAX_ALLOCATION_ATTEMPTS} attempts")


def _atomic_write_text(target: Path, text: str) -> None:
    """Sibling staging file, fsync, then `os.replace`, so a reader sees the old or the new bytes."""
    staging = target.with_name(f".{target.name}.{os.getpid()}.{secrets.token_hex(4)}.tmp")
    try:
        with open(staging, "x", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(staging, target)
    finally:
        with contextlib.suppress(OSError):
            staging.unlink(missing_ok=True)


def _strict_pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate JSON key")
        result[key] = value
    return result


def _refuse_constant(_name: str) -> None:
    raise ValueError("non-finite JSON number")


def _load_json(path: Path) -> Any:
    return json.loads(
        path.read_text(encoding="utf-8"), object_pairs_hook=_strict_pairs, parse_constant=_refuse_constant
    )


def _contained_path(run_dir: Path, value: object) -> Path:
    """The absolute path a run-relative POSIX artifact path names. ValueError when it is not a plain
    relative path or when it resolves (through links too) outside the run."""
    if not isinstance(value, str) or not value or _has_control(value) or "\\" in value or ":" in value:
        raise ValueError("an artifact path must be a non-empty run-relative POSIX path")
    if value.startswith("/") or any(part in {"", ".", ".."} for part in value.split("/")):
        raise ValueError("an artifact path must be a non-empty run-relative POSIX path")
    base = run_dir.resolve()
    target = base.joinpath(*PurePosixPath(value).parts).resolve()
    if target == base or not target.is_relative_to(base):
        raise ValueError("an artifact path resolves outside its run")
    return target


def _is_run_name(value: object) -> bool:
    return (
        isinstance(value, str)
        and bool(value)
        and not value.startswith(".")
        and not _has_control(value)
        and not any(char in value for char in "/\\:")
    )


def _invalid_text(value: object) -> bool:
    return not isinstance(value, str) or not value.strip()


def _valid_key(value: object) -> bool:
    return not _invalid_text(value) and not _has_control(value)


def _is_version(value: object, expected: int) -> bool:
    return isinstance(value, int) and not isinstance(value, bool) and value == expected


def _valid_source(source: object) -> bool:
    if not isinstance(source, dict) or set(source) != _SOURCE_KEYS or source["kind"] not in UNIT_KINDS:
        return False
    optional = (source[field] for field in SOURCE_IDENTITY_FIELDS)
    return not _invalid_text(source["name"]) and all(value is None or not _invalid_text(value) for value in optional)


def _validate_entry(entry: object, run_dir: Path) -> dict[str, Any]:
    if not isinstance(entry, dict) or set(entry) != _UNIT_KEYS or parse_unit_id(entry["id"]) is None:
        raise UnitIndexInvalid("index_invalid", "a unit entry is not {id, key, source, artifacts}")
    artifacts = entry["artifacts"]
    if not _valid_key(entry["key"]) or not _valid_source(entry["source"]):
        raise UnitIndexInvalid("index_invalid", f"unit {entry['id']} has a malformed key or source")
    if not isinstance(artifacts, dict) or set(artifacts) != set(ARTIFACT_ROLES):
        raise UnitIndexInvalid("index_invalid", f"unit {entry['id']} has malformed artifacts")
    for role in ARTIFACT_ROLES:
        if artifacts[role] is None:
            continue
        try:
            _contained_path(run_dir, artifacts[role])
        except ValueError as exc:
            raise UnitIndexInvalid("artifact_path_escapes_run", f"unit {entry['id']} {role}: {exc}") from exc
    return entry


def read_unit_index(run_dir: Path) -> list[dict[str, Any]] | None:
    """The run's validated unit entries, or None for a legacy run without an index.

    Raises `UnitIndexInvalid` (reason `index_unreadable`, `index_invalid`, `index_run_mismatch` or
    `artifact_path_escapes_run`) rather than returning a partial list."""
    run_dir = Path(run_dir)
    try:
        data = _load_json(run_dir / INDEX_FILE_NAME)
    except FileNotFoundError:
        return None
    except (OSError, UnicodeDecodeError) as exc:
        raise UnitIndexInvalid("index_unreadable", exc.__class__.__name__) from exc
    except (ValueError, RecursionError) as exc:
        raise UnitIndexInvalid("index_invalid", "not strict JSON") from exc
    if not isinstance(data, dict) or not _is_version(data.get("schema_version"), INDEX_SCHEMA_VERSION):
        raise UnitIndexInvalid("index_invalid", "schema_version is not the supported integer 1")
    if set(data) != {"schema_version", "run", "units"} or not isinstance(data["units"], list):
        raise UnitIndexInvalid("index_invalid", "the index is not {schema_version, run, units}")
    if data["run"] != run_dir.name:
        raise UnitIndexInvalid("index_run_mismatch", "the index names another run directory")
    units = [_validate_entry(entry, run_dir) for entry in data["units"]]
    for field in ("id", "key"):
        if len({entry[field] for entry in units}) != len(units):
            raise UnitIndexInvalid("index_invalid", f"two units share one {field}")
    return units


@contextlib.contextmanager
def _index_lock(run_dir: Path) -> Iterator[None]:
    """One writer per run. An existing lock is an explicit refusal, never a wait or a takeover."""
    lock = run_dir / LOCK_FILE_NAME
    try:
        descriptor = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    except FileExistsError as exc:
        raise UnitIdError(
            f"{LOCK_FILE_NAME} exists in run {run_dir.name}: another allocator is writing this run, or "
            "one crashed. Confirm none is running, then delete the lock file and retry."
        ) from exc
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(json.dumps({"pid": os.getpid(), "acquired": _utc_now()}) + "\n")
        yield
    finally:
        lock.unlink(missing_ok=True)


def _require_run(run_dir: Path) -> Path:
    run_dir = Path(run_dir)
    if not run_dir.is_absolute() or not _is_run_name(run_dir.name) or not (run_dir / _RUN_MANIFEST).is_file():
        raise UnitIdError("unit IDs live only inside an existing allocated run (absolute path holding run.json)")
    return run_dir


def _checked_request(request: object) -> UnitRequest:
    if not isinstance(request, UnitRequest) or not _valid_key(request.key) or not _valid_source(_source(request)):
        raise UnitIdError("each request needs a key, a kind in {workbook, datasource}, a name and text identities")
    return request


def _source(request: UnitRequest) -> dict[str, Any]:
    return {
        "kind": request.kind,
        "name": request.name,
        **{field: getattr(request, field) for field in SOURCE_IDENTITY_FIELDS},
    }


def _read_owned_index(run_dir: Path) -> list[dict[str, Any]]:
    """The run's entries for a writer: every ID must be reserved for exactly this run and key, so a
    hand-edited or copied index can never re-publish an ID another unit owns."""
    units = read_unit_index(run_dir) or []
    for entry in units:
        owner, reason = _read_owner(run_dir.parent, parse_unit_id(entry["id"]))
        if owner is None or owner["run"] != run_dir.name or owner["key"] != entry["key"]:
            raise UnitIdError(
                f"unit {entry['id']} in run {run_dir.name} is not reserved for this run and key "
                f"({reason or 'owner_index_mismatch'}); nothing was written"
            )
    return units


def _publish(run_dir: Path, units: list[dict[str, Any]]) -> None:
    """Validate, then atomically replace the index and regenerate its README projection."""
    for entry in units:
        _validate_entry(entry, run_dir)
    payload = {"schema_version": INDEX_SCHEMA_VERSION, "run": run_dir.name, "units": units}
    _atomic_write_text(run_dir / INDEX_FILE_NAME, json.dumps(payload, indent=2, ensure_ascii=False) + "\n")
    _atomic_write_text(run_dir / README_FILE_NAME, render_units_readme(run_dir.name, units))


def allocate_unit_ids(run_dir: Path, requests: Sequence[UnitRequest]) -> list[dict[str, Any]]:
    """Give every requested unit an ID inside one allocated run; returns entries in request order.

    A key already in this run's index keeps its ID (its source descriptors are refreshed, so a
    source rename updates display metadata); every other key reserves a fresh runs-root number,
    writes that reservation's owner pointer, and only then is the index published once. The same key
    with a different kind, or an existing entry whose ID is not reserved for this run and key, is
    refused before anything is reserved. Every successful call regenerates the README from the
    index, so an identical retry repairs an interrupted publication.
    """
    run_dir = _require_run(run_dir)
    wanted = [_checked_request(request) for request in requests]
    keys = [request.key for request in wanted]
    if len(set(keys)) != len(keys):
        raise UnitIdError("one allocation names the same unit key twice")
    with _index_lock(run_dir):
        units = _read_owned_index(run_dir)
        by_key = {entry["key"]: entry for entry in units}
        for request in wanted:
            if request.key in by_key and by_key[request.key]["source"]["kind"] != request.kind:
                raise UnitIdError(f"unit {by_key[request.key]['id']} already holds this key as another kind")
        for request in wanted:
            entry = by_key.get(request.key)
            if entry is None:
                number = _reserve(run_dir.parent)
                owner = {
                    "schema_version": OWNER_SCHEMA_VERSION,
                    "id": format_unit_id(number),
                    "run": run_dir.name,
                    "key": request.key,
                    "reserved": _utc_now(),
                }
                owner_path = reservations_root(run_dir.parent) / _reservation_name(number) / OWNER_FILE_NAME
                _atomic_write_text(owner_path, json.dumps(owner, indent=2, ensure_ascii=False) + "\n")
                entry = {
                    "id": owner["id"],
                    "key": request.key,
                    "source": _source(request),
                    "artifacts": dict.fromkeys(ARTIFACT_ROLES),
                }
                units.append(entry)
                by_key[request.key] = entry
            else:
                entry["source"] = _source(request)
        if units:
            _publish(run_dir, units)
        return [copy.deepcopy(by_key[key]) for key in keys]


def set_unit_artifacts(run_dir: Path, unit_id: str, artifacts: Mapping[str, str | None]) -> dict[str, Any]:
    """Record emitted artifact paths (run-relative POSIX, contained in the run) for one unit."""
    run_dir = _require_run(run_dir)
    if not set(artifacts) <= set(ARTIFACT_ROLES):
        raise UnitIdError(f"artifact roles are {', '.join(ARTIFACT_ROLES)}")
    for role, value in artifacts.items():
        if value is not None:
            try:
                _contained_path(run_dir, value)
            except ValueError as exc:
                raise UnitIdError(f"{role}: {exc}") from exc
    with _index_lock(run_dir):
        units = _read_owned_index(run_dir)
        entry = next((item for item in units if item["id"] == unit_id), None)
        if entry is None:
            raise UnitIdError("that unit ID is not allocated in this run")
        entry["artifacts"].update(artifacts)
        _publish(run_dir, units)
        return copy.deepcopy(entry)


def _markdown(text: str) -> str:
    """Escape a customer label for one Markdown table cell; control characters become visible."""
    out = []
    for char in text:
        if _has_control(char):
            out.append(f"\\u{ord(char):04x}")
        elif char in _MARKDOWN_SPECIAL:
            out.append("\\" + char)
        else:
            out.append(char)
    return "".join(out)


def _artifact_cell(entry: dict[str, Any]) -> str:
    for role in _ARTIFACT_PREFERENCE[entry["source"]["kind"]]:
        relative = entry["artifacts"][role]
        if relative is not None:
            label = _markdown(PurePosixPath(relative).name)
            return f"[{label}]({quote(relative, safe='/')}) ({role.replace('_', ' ')})"
    return "not emitted"


def render_units_readme(run_name: str, units: Sequence[dict[str, Any]]) -> str:
    """The human projection of one run's index. Generated only from the index entries."""
    lines = [
        _README_MARKER,
        f"# Units in run {_markdown(run_name)}",
        "",
        "Generated from `unit-index.json`, the authority; regenerated whenever the index changes.",
        "Local only: original names are private customer inventory. Never commit or publish this file.",
        "A short ID is a lookup key, not proof of source identity: `t2p units show <id>`.",
        "",
        "| ID | Kind | Original name | Project | Local artifact |",
        "|---|---|---|---|---|",
    ]
    for entry in units:
        source = entry["source"]
        project = _markdown(source["project_name"]) if source["project_name"] is not None else "unknown"
        lines.append(
            f"| {entry['id']} | {source['kind'].capitalize()} | {_markdown(source['name'])} | {project} | "
            f"{_artifact_cell(entry)} |"
        )
    identified = [entry for entry in units if any(entry["source"][f] for f in ("luid", "site_luid", "project_luid"))]
    if identified:
        lines.extend(["", "## Source identities", ""])
        for entry in identified:
            known = [
                f"{field}={_markdown(entry['source'][field])}"
                for field in ("luid", "site_luid", "project_luid")
                if entry["source"][field]
            ]
            lines.append(f"- {entry['id']}: " + ", ".join(known))
    return "\n".join(lines) + "\n"


def _read_owner(runs_root: Path, number: int) -> tuple[dict[str, Any] | None, str]:
    """`(owner, "")`, or `(None, reason)` when the reservation cannot name its owner."""
    reservation = reservations_root(runs_root) / _reservation_name(number)
    try:
        if not stat.S_ISDIR(os.stat(reservation).st_mode):
            return None, "reservation_unreadable"
        owner = _load_json(reservation / OWNER_FILE_NAME)
    except FileNotFoundError:
        # No reservation at all is "never reserved"; a reservation whose pointer never landed was
        # interrupted (or is still being written) and is never reused.
        return None, "reservation_interrupted" if os.path.isdir(reservation) else "never_reserved"
    except (OSError, ValueError, RecursionError):
        return None, "owner_pointer_invalid"
    if (
        not isinstance(owner, dict)
        or set(owner) != _OWNER_KEYS
        or not _is_version(owner["schema_version"], OWNER_SCHEMA_VERSION)
        or owner["id"] != format_unit_id(number)
        or not _is_run_name(owner["run"])
    ):
        return None, "owner_pointer_invalid"
    if not _valid_key(owner["key"]):
        return None, "owner_pointer_invalid"
    return owner, ""


def _artifact_view(run_dir: Path, artifacts: dict[str, Any]) -> dict[str, Any]:
    view: dict[str, Any] = {}
    for role in ARTIFACT_ROLES:
        relative = artifacts[role]
        path = None if relative is None else _contained_path(run_dir, relative)
        view[role] = None if path is None else {"relative_path": relative, "path": str(path), "exists": path.exists()}
    return view


def _candidate(
    unit_id: str, reason: str, run_dir: Path | None = None, entry: dict[str, Any] | None = None
) -> dict[str, Any]:
    return {
        "id": unit_id,
        "state": "unassessable" if reason else "found",
        "reason": reason or None,
        "run": None if run_dir is None else run_dir.name,
        "run_path": None if run_dir is None else str(run_dir),
        "key": None if entry is None else entry["key"],
        "source": None if entry is None else dict(entry["source"]),
        "artifacts": None if entry is None or run_dir is None else _artifact_view(run_dir, entry["artifacts"]),
    }


def _lookup(action: str, root: Path, result: str, reason: str | None, query: dict, **rows: list) -> dict[str, Any]:
    return {
        "schema_version": LOOKUP_SCHEMA_VERSION,
        "action": action,
        "result": result,
        "reason": reason,
        "query": query,
        "runs_root": str(root),
        "candidates": rows.get("candidates", []),
        "runs": rows.get("runs", []),
    }


def show_unit(runs_root: Path, unit_id: str) -> dict[str, Any]:
    """Resolve one ID through its owner pointer, with no run argument (D1). Read-only."""
    root = Path(runs_root)
    number = parse_unit_id(unit_id)
    if number is None:
        return _lookup("show", root, "missing", "malformed_unit_id", {"id": None})
    canonical = format_unit_id(number)
    owner, reason = _read_owner(root, number)
    if owner is None:
        if reason == "never_reserved":
            return _lookup("show", root, "missing", reason, {"id": canonical})
        return _lookup(
            "show", root, "unassessable", reason, {"id": canonical}, candidates=[_candidate(canonical, reason)]
        )
    run_dir = root / owner["run"]
    units: list[dict[str, Any]] | None = None
    try:
        is_dir = stat.S_ISDIR(os.stat(run_dir).st_mode)
        units = read_unit_index(run_dir) if is_dir else None
        reason = "owner_run_missing" if not is_dir else "owner_index_missing" if units is None else ""
    except FileNotFoundError:
        reason = "owner_run_missing"
    except OSError:
        reason = "owner_run_unreadable"
    except UnitIndexInvalid as exc:
        reason = exc.reason
    entry = next((item for item in units or [] if item["id"] == canonical), None)
    if units is not None and (entry is None or entry["key"] != owner["key"]):
        entry, reason = None, "owner_index_mismatch"
    candidate = _candidate(canonical, reason, run_dir, entry)
    return _lookup("show", root, candidate["state"], candidate["reason"], {"id": canonical}, candidates=[candidate])


def _survey(root: Path) -> tuple[list[dict[str, Any]], list[dict[str, Any]], str | None]:
    """Every run under the root with its index state, and every indexed unit checked against its
    owner pointer. Uses work_dirs' one discovery site, so allocator metadata is never a run."""
    run_dirs, root_problem = work_dirs._discover_run_dirs(root)  # pylint: disable=protected-access
    runs: list[dict[str, Any]] = []
    candidates: list[dict[str, Any]] = []
    for run_dir in run_dirs:
        row = {"run": run_dir.name, "run_path": str(run_dir), "state": "indexed", "reason": None, "unit_count": 0}
        runs.append(row)
        try:
            units = read_unit_index(run_dir)
        except UnitIndexInvalid as exc:
            row.update(state="unassessable", reason=exc.reason, unit_count=None)
            continue
        if units is None:
            row.update(state="legacy", reason="no_unit_index", unit_count=None)
            continue
        row["unit_count"] = len(units)
        for entry in units:
            owner, reason = _read_owner(root, parse_unit_id(entry["id"]))
            if owner is None:
                reason = {
                    "never_reserved": "reservation_missing",
                    "reservation_interrupted": "owner_pointer_missing",
                }.get(reason, reason)
            elif owner["run"] != run_dir.name or owner["key"] != entry["key"]:
                reason = "owner_index_mismatch"
            candidates.append(_candidate(entry["id"], reason, run_dir, entry))
    repeated = Counter(candidate["id"] for candidate in candidates)
    for candidate in candidates:
        if repeated[candidate["id"]] > 1:
            candidate.update(state="unassessable", reason="unit_id_in_multiple_runs")
    return runs, candidates, root_problem


def _blocking_reason(root_problem: str | None, runs: list[dict], candidates: list[dict]) -> str | None:
    if root_problem is not None:
        return "runs_root_unreadable"
    for row in [*runs, *candidates]:
        if row["state"] == "unassessable":
            return row["reason"]
    return None


def list_units(runs_root: Path) -> dict[str, Any]:
    """Every allocated unit under one runs root, plus legacy and unassessable runs. Read-only."""
    root = Path(runs_root)
    runs, candidates, root_problem = _survey(root)
    blocking = _blocking_reason(root_problem, runs, candidates)
    if blocking is not None:
        result, reason = "unassessable", blocking
    elif candidates:
        result, reason = "found", None
    elif any(row["state"] == "legacy" for row in runs):
        result, reason = "legacy", "no_unit_index"
    else:
        result, reason = "missing", "no_units"
    return _lookup("list", root, result, reason, {}, candidates=candidates, runs=runs)


def find_units(runs_root: Path, *, name: str | None = None, luid: str | None = None) -> dict[str, Any]:
    """All units whose original name contains `name` (case-insensitive) and/or whose source LUID is
    `luid`. Several matches are `ambiguous` with every candidate listed; none is ever picked."""
    if name is None and luid is None:
        raise ValueError("find needs a name or a LUID")
    root = Path(runs_root)
    runs, candidates, root_problem = _survey(root)
    matches = [
        candidate
        for candidate in candidates
        if (name is None or name.casefold() in candidate["source"]["name"].casefold())
        and (luid is None or (candidate["source"]["luid"] or "").casefold() == luid.casefold())
    ]
    blocking = _blocking_reason(root_problem, runs, matches)
    if blocking is not None:
        result, reason = "unassessable", blocking
    elif len(matches) > 1:
        result, reason = "ambiguous", "multiple_candidates"
    elif matches:
        result, reason = "found", None
    elif any(row["state"] == "legacy" for row in runs):
        result, reason = "legacy", "legacy_runs_not_searched"
    else:
        result, reason = "missing", "no_match"
    return _lookup("find", root, result, reason, {"name": name, "luid": luid}, candidates=matches, runs=runs)


def lookup_exit_code(lookup: dict[str, Any]) -> int:
    """3 unassessable; 0 found (and any assessable list); 1 missing, ambiguous or legacy."""
    if lookup["result"] == "unassessable":
        return 3
    return 0 if lookup["action"] == "list" or lookup["result"] == "found" else 1

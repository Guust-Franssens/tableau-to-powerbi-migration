    assert _compare(wire=padded, typed_max_payload_bytes=len(padded) - 1) == "PAYLOAD_LIMIT"
    assert _compare(wire=padded, typed_max_payload_bytes=len(WIRE)) == "PAYLOAD_LIMIT"



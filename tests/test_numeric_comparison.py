def test_composite_keys_are_tuples_not_delimiter_concatenations() -> None:
    """These two keys collide if their components are joined with a pipe."""
    csv = b"Region,Item,Amount\na|b,c,1\na,b|c,2\n"
    payload = _payload()
    payload["rows"] = [_row("a|b", "c", "1"), _row("a", "b|c", "2")]
    assert _compare(csv, _wire(payload)) == "EQUAL"
    payload["rows"][0][2]["value"], payload["rows"][1][2]["value"] = "2", "1"
    assert _compare(csv, _wire(payload)) == "DIFFERENT"


def test_rows_and_explicitly_mapped_columns_can_be_reordered() -> None:
    """Order is immaterial; complete keyed identity and mapped values are not."""
    payload = _payload()
    order = (2, 0, 1)
    payload["columns"] = [payload["columns"][index] for index in order]
    payload["rows"] = [[row[index] for index in order] for row in reversed(payload["rows"])]
    assert _compare(wire=_wire(payload)) == "EQUAL"


@pytest.mark.parametrize("variant", ["missing", "extra", "changed"])
def test_different_unique_key_sets_are_different(variant: str) -> None:
    """A missing, additional, or substituted DAX key is a valid difference."""

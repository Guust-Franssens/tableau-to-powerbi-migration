def test_one_explicit_key_and_every_mapped_numeric_value_are_compared() -> None:
    """A second numeric value is not an ignored column; a single text-key component is sufficient."""
    csv = b"Key,Small,Large,Amount\nA,7,9223372036854775807,9007199254740993.1250\n"
    payload = {
        "schema_version": 1,
        "query_sha256": "0" * 64,
        "columns": [
            {"name": "k", "kind": "string"},
            {"name": "s", "kind": "int32"},
            {"name": "l", "kind": "int64"},
            {"name": "a", "kind": "decimal"},
        ],
        "rows": [
            [
                {"kind": "string", "value": "A"},
                {"kind": "int32", "value": "7"},
                {"kind": "int64", "value": "9223372036854775807"},
                {"kind": "decimal", "value": "9007199254740993.1250"},
            ]
        ],
    }
    mapping = {"key_columns": (("Key", "k"),), "value_columns": (("Small", "s"), ("Large", "l"), ("Amount", "a"))}
    assert _compare(csv, _wire(payload), **mapping) == "EQUAL"
    for index, changed in ((1, "8"), (2, "9223372036854775806"), (3, "9007199254740993.1251")):
        original = payload["rows"][0][index]["value"]
        payload["rows"][0][index]["value"] = changed
        assert _compare(csv, _wire(payload), **mapping) == "DIFFERENT"
        payload["rows"][0][index]["value"] = original



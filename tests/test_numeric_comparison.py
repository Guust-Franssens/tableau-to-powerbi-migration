@pytest.mark.parametrize("side", ["csv", "typed"])
@pytest.mark.parametrize("changed_value", [False, True])
def test_duplicate_keys_refuse_instead_of_deduplicating(side: str, changed_value: bool) -> None:
    """Both identical and value-conflicting duplicate keys are outside the domain."""
    if side == "csv":
        extra = b"North,A,7\n" if changed_value else b"North,A,9007199254740993.1250\n"
        result = _compare(CSV + extra)
    else:
        payload = _payload()
        amount = "7" if changed_value else "9007199254740993.1250"
        payload["rows"].append(_row("North", "A", amount))
        result = _compare(wire=_wire(payload))
    assert result == "KEY_DUPLICATE"



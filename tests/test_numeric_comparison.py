def test_exact_original_byte_limits_and_one_byte_over() -> None:
    """Charge the original CSV and whole wire envelope, not a smaller JSON serialization."""
    padded = b" \t" + WIRE + b"  "
    assert _compare(wire=padded, csv_max_payload_bytes=len(CSV), typed_max_payload_bytes=len(padded)) == "EQUAL"
